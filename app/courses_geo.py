def layer_diagram(layers, color="#1f8a8a", h=200):
    """
    大气垂直分层示意（从下往上）
    layers: [(名称, 高度标注, 特点), ...]  自下而上
    """
    n = len(layers)
    band = (h - 24) / n
    out = [f'<svg viewBox="0 0 320 {h}" xmlns="http://www.w3.org/2000/svg" '
           f'style="width:100%;height:auto;display:block">']
    cols = ["#eaf6f6", "#dceeee", "#cfe6e6", "#c2dfdf"]
    for i, (name, alt, feat) in enumerate(layers):
        y = (h - 12) - (i + 1) * band
        out.append(f'<rect x="34" y="{y:.1f}" width="256" height="{band:.1f}" '
                   f'fill="{cols[i % len(cols)]}" stroke="{color}" stroke-width="1"/>')
        out.append(f'<text x="42" y="{y+band/2+4:.1f}" font-size="11.5" '
                   f'font-weight="700" fill="#1c5f5f">{name}</text>')
        out.append(f'<text x="284" y="{y+band/2+4:.1f}" font-size="9.5" '
                   f'fill="#5a7d7d" text-anchor="end">{alt}</text>')
    out.append(f'<line x1="34" y1="12" x2="34" y2="{h-12}" stroke="{color}" stroke-width="1.6"/>')
    out.append(f'<text x="22" y="{h/2}" font-size="9.5" fill="{color}" '
               f'text-anchor="middle" transform="rotate(-90 22 {h/2})">海拔升高</text>')
    out.append('</svg>')
    return "".join(out)


