# 汇总：cid → 论述题列表
ESSAY_BANK = {
    "p1": P1_ESSAY,
    "p2": P2_ESSAY,
    "p3": P3_ESSAY,
    "p4": P4_ESSAY,
}


def attach_essay(courses):
    """
    把论述题库挂到课程结构上（courses.py 调用）。

    courses 里的每门课若有对应的 ESSAY_BANK 条目，就加上 quiz_essay 字段，
    bank.seed_from_courses 会自动把它播种为 tier=essay 的题目。
    这样 courses.py 不必关心论述题的存放位置。
    """
    for c in courses:
        qs = ESSAY_BANK.get(c.get("id"))
        if qs:
            c["quiz_essay"] = qs
    return courses
